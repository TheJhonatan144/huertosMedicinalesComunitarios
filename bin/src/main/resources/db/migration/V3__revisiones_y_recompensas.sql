-- V3: revisiones (historial inmutable) y recompensas (libro de movimientos inmutable).

CREATE TABLE revision (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    envio_id      BIGINT      NOT NULL UNIQUE REFERENCES envio_evidencia (id),  -- una sola decisión por envío
    revisor_id    BIGINT      NOT NULL REFERENCES usuario (id),
    decision      VARCHAR(15) NOT NULL CHECK (decision IN ('APROBADA', 'RECHAZADA')),
    observaciones TEXT,
    revisada_en   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (decision = 'APROBADA' OR length(btrim(coalesce(observaciones, ''))) > 0)
);

-- El revisor debe ser un ADMIN_EVIDENCIAS activo, tener asignada la comunidad y no ser quien registró la actividad.
CREATE FUNCTION validar_revisor() RETURNS trigger AS $$
DECLARE
    v_comunidad   BIGINT;
    v_registrante BIGINT;
BEGIN
    SELECT a.comunidad_id, a.registrada_por INTO v_comunidad, v_registrante
      FROM envio_evidencia e JOIN actividad a ON a.id = e.actividad_id
     WHERE e.id = NEW.envio_id;
    IF v_registrante = NEW.revisor_id THEN
        RAISE EXCEPTION 'autorrevision_prohibida' USING ERRCODE = '23514';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM asignacion_revisor
                    WHERE usuario_id = NEW.revisor_id AND comunidad_id = v_comunidad) THEN
        RAISE EXCEPTION 'revisor_no_asignado' USING ERRCODE = '23514';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM usuario
                    WHERE id = NEW.revisor_id AND rol = 'ADMIN_EVIDENCIAS' AND activo) THEN
        RAISE EXCEPTION 'revisor_sin_rol' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_revision_valida BEFORE INSERT ON revision
    FOR EACH ROW EXECUTE FUNCTION validar_revisor();
CREATE TRIGGER trg_revision_inmutable BEFORE UPDATE OR DELETE ON revision
    FOR EACH ROW EXECUTE FUNCTION bloquear_modificacion();

-- Puntos individuales: una fila por (actividad, integrante).
CREATE TABLE recompensa_individual (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actividad_id  BIGINT      NOT NULL,
    integrante_id BIGINT      NOT NULL,
    comunidad_id  BIGINT      NOT NULL,
    puntos        INTEGER     NOT NULL CHECK (puntos > 0),
    creada_en     TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (actividad_id, integrante_id),
    FOREIGN KEY (actividad_id, comunidad_id)  REFERENCES actividad (id, comunidad_id),
    FOREIGN KEY (integrante_id, comunidad_id) REFERENCES integrante (id, comunidad_id)
);

-- Puntos comunitarios y progreso del huerto: una fila por actividad.
CREATE TABLE recompensa_comunitaria (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actividad_id  BIGINT      NOT NULL UNIQUE,
    comunidad_id  BIGINT      NOT NULL,
    puntos        INTEGER     NOT NULL CHECK (puntos >= 0),
    progreso      INTEGER     NOT NULL CHECK (progreso >= 0),
    creada_en     TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (actividad_id, comunidad_id) REFERENCES actividad (id, comunidad_id)
);

-- Solo una actividad APROBADA puede generar recompensas; las individuales, solo para su lista fijada.
CREATE FUNCTION validar_recompensa_comunitaria() RETURNS trigger AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM actividad WHERE id = NEW.actividad_id AND estado = 'APROBADA') THEN
        RAISE EXCEPTION 'actividad_no_aprobada: no se generan puntos ni progreso' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE FUNCTION validar_recompensa_individual() RETURNS trigger AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM actividad WHERE id = NEW.actividad_id AND estado = 'APROBADA') THEN
        RAISE EXCEPTION 'actividad_no_aprobada: no se generan puntos ni progreso' USING ERRCODE = '23514';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM actividad_participante
                    WHERE actividad_id = NEW.actividad_id AND integrante_id = NEW.integrante_id) THEN
        RAISE EXCEPTION 'no_participante: el integrante no estaba en la lista de la actividad' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_recomp_ind_valida BEFORE INSERT ON recompensa_individual
    FOR EACH ROW EXECUTE FUNCTION validar_recompensa_individual();
CREATE TRIGGER trg_recomp_com_valida BEFORE INSERT ON recompensa_comunitaria
    FOR EACH ROW EXECUTE FUNCTION validar_recompensa_comunitaria();
CREATE TRIGGER trg_recomp_ind_inmutable BEFORE UPDATE OR DELETE ON recompensa_individual
    FOR EACH ROW EXECUTE FUNCTION bloquear_modificacion();
CREATE TRIGGER trg_recomp_com_inmutable BEFORE UPDATE OR DELETE ON recompensa_comunitaria
    FOR EACH ROW EXECUTE FUNCTION bloquear_modificacion();
