ALTER TABLE usuario DROP CONSTRAINT usuario_rol_check;
ALTER TABLE usuario ADD CONSTRAINT usuario_rol_check
    CHECK (rol IN ('GESTOR_HUERTO', 'PARTICIPANTE', 'ADMIN_MINISTERIO_SALUD', 'SIN_ASIGNAR', 'ADMIN_TECNICO'));

CREATE TABLE historial_asignacion_revisor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comunidad_id BIGINT NOT NULL REFERENCES comunidad(id),
    revisor_anterior_id BIGINT REFERENCES usuario(id),
    revisor_nuevo_id BIGINT NOT NULL REFERENCES usuario(id),
    actor_tecnico_id BIGINT NOT NULL REFERENCES usuario(id),
    motivo TEXT NOT NULL,
    cambiada_en TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_historial_asignacion_comunidad ON historial_asignacion_revisor(comunidad_id, cambiada_en DESC);
