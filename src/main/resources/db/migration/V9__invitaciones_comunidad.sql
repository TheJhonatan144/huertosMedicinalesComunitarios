CREATE TABLE invitacion_comunidad (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comunidad_id          BIGINT      NOT NULL REFERENCES comunidad (id),
    invitada_por          BIGINT      NOT NULL REFERENCES usuario (id),
    usuario_destino_id    BIGINT      NOT NULL REFERENCES usuario (id),
    tipo                  VARCHAR(20) NOT NULL CHECK (tipo IN ('PARTICIPANTE', 'TRASPASO_GESTOR')),
    estado                VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE', 'ACEPTADA', 'RECHAZADA', 'CANCELADA')),
    creada_en             TIMESTAMPTZ NOT NULL DEFAULT now(),
    respondida_en         TIMESTAMPTZ
);
CREATE UNIQUE INDEX uq_invitacion_pendiente_destino
    ON invitacion_comunidad (comunidad_id, usuario_destino_id, tipo)
    WHERE estado = 'PENDIENTE';
CREATE INDEX ix_invitacion_destino_estado
    ON invitacion_comunidad (usuario_destino_id, estado, creada_en DESC);
