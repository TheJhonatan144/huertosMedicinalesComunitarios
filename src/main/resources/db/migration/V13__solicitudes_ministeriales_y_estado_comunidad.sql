-- Se conserva el expediente de decisión incluso después de borrar una comunidad.
-- comunidad_id es intencionalmente una referencia lógica, sin FK, para conservar el expediente.
CREATE TABLE solicitud_comunidad (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo               VARCHAR(20) NOT NULL CHECK (tipo IN ('CREAR', 'ELIMINAR')),
    estado             VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
                           CHECK (estado IN ('PENDIENTE', 'APROBADA', 'RECHAZADA')),
    solicitante_id     BIGINT NOT NULL REFERENCES usuario(id),
    comunidad_id       BIGINT,
    nombre_comunidad   VARCHAR(120) NOT NULL DEFAULT '',
    datos_json         TEXT,
    motivo_solicitud   TEXT,
    motivo_rechazo     TEXT,
    revisada_por       BIGINT REFERENCES usuario(id),
    creada_en          TIMESTAMPTZ NOT NULL DEFAULT now(),
    revisada_en        TIMESTAMPTZ,
    CHECK ((tipo = 'CREAR' AND ((estado = 'PENDIENTE' AND datos_json IS NOT NULL)
                                OR (estado <> 'PENDIENTE' AND datos_json IS NULL)))
           OR (tipo = 'ELIMINAR' AND comunidad_id IS NOT NULL)),
    CHECK ((estado <> 'RECHAZADA') OR length(btrim(coalesce(motivo_rechazo, ''))) > 0)
);
CREATE UNIQUE INDEX uq_solicitud_creacion_pendiente
    ON solicitud_comunidad(solicitante_id) WHERE tipo = 'CREAR' AND estado = 'PENDIENTE';
CREATE UNIQUE INDEX uq_solicitud_eliminacion_pendiente
    ON solicitud_comunidad(comunidad_id) WHERE tipo = 'ELIMINAR' AND estado = 'PENDIENTE';
CREATE INDEX ix_solicitud_comunidad_estado
    ON solicitud_comunidad(estado, creada_en) WHERE estado = 'PENDIENTE';

-- Cola duradera para borrar las fotos tras confirmar la transacción de eliminación.
CREATE TABLE archivo_borrado_pendiente (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id        BIGINT NOT NULL REFERENCES solicitud_comunidad(id),
    clave_almacenamiento VARCHAR(200) NOT NULL UNIQUE,
    creada_en           TIMESTAMPTZ NOT NULL DEFAULT now(),
    intentos            INTEGER NOT NULL DEFAULT 0,
    ultimo_error        TEXT
);

-- Solo permite saltar la inmutabilidad para registros que pertenecen a una eliminación aprobada.
CREATE OR REPLACE FUNCTION bloquear_modificacion() RETURNS trigger AS $$
DECLARE
    solicitud_borrado BIGINT;
    comunidad_borrada BIGINT;
BEGIN
    IF TG_OP = 'DELETE' THEN
        solicitud_borrado := nullif(current_setting('app.solicitud_comunidad_borrado', true), '')::BIGINT;
        IF solicitud_borrado IS NOT NULL THEN
            IF TG_TABLE_NAME IN ('actividad_participante', 'recompensa_individual', 'recompensa_comunitaria') THEN
                comunidad_borrada := (to_jsonb(OLD)->>'comunidad_id')::BIGINT;
            ELSIF TG_TABLE_NAME = 'envio_evidencia' THEN
                SELECT a.comunidad_id INTO comunidad_borrada
                  FROM actividad a WHERE a.id = (to_jsonb(OLD)->>'actividad_id')::BIGINT;
            ELSIF TG_TABLE_NAME = 'revision' THEN
                SELECT a.comunidad_id INTO comunidad_borrada
                  FROM envio_evidencia e JOIN actividad a ON a.id = e.actividad_id
                 WHERE e.id = (to_jsonb(OLD)->>'envio_id')::BIGINT;
            END IF;
            IF EXISTS (
                SELECT 1 FROM solicitud_comunidad s
                 WHERE s.id = solicitud_borrado AND s.tipo = 'ELIMINAR'
                   AND s.estado = 'APROBADA' AND s.comunidad_id = comunidad_borrada
            ) THEN
                RETURN OLD;
            END IF;
        END IF;
    END IF;
    RAISE EXCEPTION 'registro_inmutable: % sobre % no está permitido', TG_OP, TG_TABLE_NAME
        USING ERRCODE = '23514';
END;
$$ LANGUAGE plpgsql;

-- Cambia la verificación de rol almacenada en el disparador de revisión.
CREATE OR REPLACE FUNCTION validar_revisor() RETURNS trigger AS $$
DECLARE
    v_comunidad   BIGINT;
    v_registrante BIGINT;
BEGIN
    SELECT a.comunidad_id, a.registrada_por INTO v_comunidad, v_registrante
      FROM envio_evidencia e JOIN actividad a ON a.id = e.actividad_id
     WHERE e.id = NEW.envio_id;
    IF v_registrante = NEW.revisor_id THEN
        RAISE EXCEPTION 'autorrevision_prohibida' USING ERRCODE = '23514';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM asignacion_revisor
                    WHERE usuario_id = NEW.revisor_id AND comunidad_id = v_comunidad) THEN
        RAISE EXCEPTION 'revisor_no_asignado' USING ERRCODE = '23514';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM usuario
                    WHERE id = NEW.revisor_id AND rol = 'ADMIN_MINISTERIO_SALUD' AND activo) THEN
        RAISE EXCEPTION 'revisor_sin_rol' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
