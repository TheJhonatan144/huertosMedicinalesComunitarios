CREATE TABLE especie (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version BIGINT NOT NULL DEFAULT 0,
 nombre_comun VARCHAR(100) NOT NULL,
 nombre_cientifico VARCHAR(120), otros_nombres VARCHAR(250), familia_botanica VARCHAR(120),
 altitud_minima INTEGER CHECK (altitud_minima BETWEEN 0 AND 6500),
 altitud_maxima INTEGER CHECK (altitud_maxima BETWEEN 0 AND 6500),
 provincias VARCHAR(600), clima VARCHAR(600),
 ciclo VARCHAR(10) CHECK (ciclo IN ('CORTO','LARGO')),
 cualidad VARCHAR(10) CHECK (cualidad IN ('CALIENTE','FRIA')),
 usos_medicinales TEXT, saberes TEXT, fuente_documental VARCHAR(2000), foto_fuente VARCHAR(1000),
 foto_clave VARCHAR(200), foto_tipo VARCHAR(30) CHECK (foto_tipo IN ('image/png','image/jpeg')),
 CHECK (altitud_minima IS NULL OR altitud_maxima IS NULL OR altitud_minima <= altitud_maxima),
 CHECK ((foto_clave IS NULL) = (foto_tipo IS NULL)),
 CHECK ((NULLIF(btrim(usos_medicinales),'') IS NULL AND NULLIF(btrim(saberes),'') IS NULL AND cualidad IS NULL)
        OR NULLIF(btrim(fuente_documental),'') IS NOT NULL)
);
CREATE TABLE especie_region (
 especie_id BIGINT NOT NULL REFERENCES especie(id),
 region VARCHAR(20) NOT NULL CHECK (region IN ('COSTA','SIERRA','AMAZONIA','INSULAR')),
 PRIMARY KEY (especie_id,region)
);
