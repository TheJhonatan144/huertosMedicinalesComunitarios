CREATE TABLE espacio_huerto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    huerto_id BIGINT NOT NULL REFERENCES huerto(id) ON DELETE CASCADE,
    nombre VARCHAR(100) NOT NULL,
    diseno VARCHAR(40) NOT NULL CHECK (diseno IN (
        'TIERRA_SURCOS', 'TIERRA_CAMADAS', 'TIERRA_CAMELLONES', 'TIERRA_TERRAZAS',
        'VERTICAL_PAREDES', 'COLGANTE_TECHOS', 'PISO_MACETAS', 'PISO_BOTELLAS_PATIO',
        'PISO_LLANTAS_PATIO', 'PISO_TERRAZA', 'PISO_GRADAS', 'PISO_BALCONES', 'PISO_FILOS_VENTANA'
    )),
    area_m2 NUMERIC(10,2) NOT NULL CHECK (area_m2 > 0),
    descripcion VARCHAR(500) NOT NULL DEFAULT '',
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    creada_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (huerto_id, nombre)
);
CREATE INDEX ix_espacio_huerto ON espacio_huerto(huerto_id, activa);

