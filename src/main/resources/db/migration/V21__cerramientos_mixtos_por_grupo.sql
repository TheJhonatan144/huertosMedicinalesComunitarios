-- Conserva el detalle anterior y registra los grupos de cerramiento que pueden coexistir.
CREATE TABLE huerto_cerramiento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    huerto_id BIGINT NOT NULL REFERENCES huerto(id) ON DELETE CASCADE,
    grupo VARCHAR(20) NOT NULL CHECK (grupo IN ('NATURAL', 'REUTILIZADO', 'CONSTRUIDO')),
    CONSTRAINT uq_huerto_cerramiento_grupo UNIQUE (huerto_id, grupo)
);

INSERT INTO huerto_cerramiento (huerto_id, grupo)
SELECT id,
       CASE
           WHEN cerramiento IN ('VIVO', 'NATURAL') OR left(cerramiento, 5) = 'VIVO_'
                OR left(cerramiento, 8) = 'NATURAL_' THEN 'NATURAL'
           WHEN cerramiento = 'RECICLADO' OR left(cerramiento, 10) = 'RECICLADO_' THEN 'REUTILIZADO'
           ELSE 'CONSTRUIDO'
       END
FROM huerto
WHERE cerramiento IS NOT NULL;

-- Una huerta puede no tener cerca de estos tipos; en ese caso no se elige una al azar.
ALTER TABLE huerto ALTER COLUMN cerramiento DROP NOT NULL;
