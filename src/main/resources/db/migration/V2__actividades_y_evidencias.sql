-- V2: actividades, participantes fijados y envíos de evidencia fotográfica.

CREATE FUNCTION bloquear_modificacion() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'registro_inmutable: % sobre % no está permitido', TG_OP, TG_TABLE_NAME
        USING ERRCODE = '23514';
END;
$$ LANGUAGE plpgsql;

CREATE TABLE actividad (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comunidad_id          BIGINT      NOT NULL REFERENCES comunidad (id),
    huerto_id             BIGINT      NOT NULL REFERENCES huerto (id),
    registrada_por        BIGINT      NOT NULL REFERENCES usuario (id),
    tipo                  VARCHAR(30) NOT NULL
        CHECK (tipo IN ('RIEGO', 'SIEMBRA', 'DESHIERBE', 'ABONADO_ORGANICO', 'COSECHA', 'MANTENIMIENTO')),
    descripcion           TEXT        NOT NULL,
    fecha_actividad       DATE        NOT NULL,
    estado                VARCHAR(15) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE', 'APROBADA', 'RECHAZADA')),
    participantes_fijados BOOLEAN     NOT NULL DEFAULT FALSE,
    version               BIGINT      NOT NULL DEFAULT 0,
    creada_en             TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizada_en        TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (id, comunidad_id)
);
CREATE INDEX ix_actividad_comunidad ON actividad (comunidad_id, creada_en DESC);

-- Los participantes se fijan al registrar la actividad. Las claves compuestas impiden mezclar comunidades.
CREATE TABLE actividad_participante (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actividad_id  BIGINT NOT NULL,
    integrante_id BIGINT NOT NULL,
    comunidad_id  BIGINT NOT NULL,
    UNIQUE (actividad_id, integrante_id),
    FOREIGN KEY (actividad_id, comunidad_id)  REFERENCES actividad (id, comunidad_id),
    FOREIGN KEY (integrante_id, comunidad_id) REFERENCES integrante (id, comunidad_id)
);

CREATE FUNCTION validar_alta_participante() RETURNS trigger AS $$
DECLARE
    fijados BOOLEAN;
BEGIN
    SELECT participantes_fijados INTO fijados FROM actividad WHERE id = NEW.actividad_id;
    IF fijados THEN
        RAISE EXCEPTION 'participantes_fijados: la lista de la actividad % ya no puede cambiar', NEW.actividad_id
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_participante_alta BEFORE INSERT ON actividad_participante
    FOR EACH ROW EXECUTE FUNCTION validar_alta_participante();
CREATE TRIGGER trg_participante_inmutable BEFORE UPDATE OR DELETE ON actividad_participante
    FOR EACH ROW EXECUTE FUNCTION bloquear_modificacion();

CREATE TABLE envio_evidencia (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actividad_id         BIGINT       NOT NULL REFERENCES actividad (id),
    numero               INTEGER      NOT NULL CHECK (numero >= 1),
    clave_almacenamiento VARCHAR(200) NOT NULL UNIQUE,
    nombre_original      VARCHAR(120) NOT NULL,
    tipo_contenido       VARCHAR(30)  NOT NULL CHECK (tipo_contenido IN ('image/jpeg', 'image/png')),
    tamano_bytes         BIGINT       NOT NULL CHECK (tamano_bytes > 0),
    sha256               VARCHAR(64)  NOT NULL,
    comentario           TEXT,
    estado               VARCHAR(15)  NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE', 'APROBADA', 'RECHAZADA')),
    enviado_en           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version              BIGINT       NOT NULL DEFAULT 0,
    UNIQUE (actividad_id, numero)
);
-- A lo sumo un envío pendiente y un envío aprobado por actividad.
CREATE UNIQUE INDEX uq_envio_pendiente ON envio_evidencia (actividad_id) WHERE estado = 'PENDIENTE';
CREATE UNIQUE INDEX uq_envio_aprobado  ON envio_evidencia (actividad_id) WHERE estado = 'APROBADA';
CREATE INDEX ix_envio_estado ON envio_evidencia (estado, enviado_en);

-- El historial de envíos no se borra.
CREATE TRIGGER trg_envio_sin_borrado BEFORE DELETE ON envio_evidencia
    FOR EACH ROW EXECUTE FUNCTION bloquear_modificacion();
