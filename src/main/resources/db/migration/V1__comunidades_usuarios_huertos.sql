-- V1: usuarios, comunidades, integrantes, asignación de revisores, huertos y plantas.

CREATE TABLE usuario (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario   VARCHAR(50)  NOT NULL UNIQUE,
    nombre_completo  VARCHAR(120) NOT NULL,
    clave_hash       VARCHAR(100) NOT NULL,
    rol              VARCHAR(30)  NOT NULL
        CHECK (rol IN ('GESTOR_HUERTO', 'PARTICIPANTE', 'ADMIN_EVIDENCIAS')),
    activo           BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en        TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE comunidad (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(120)     NOT NULL UNIQUE,
    descripcion  TEXT             NOT NULL,
    provincia    VARCHAR(60)      NOT NULL,
    canton       VARCHAR(60)      NOT NULL,
    latitud      DOUBLE PRECISION NOT NULL CHECK (latitud BETWEEN -5.1 AND 1.8),
    longitud     DOUBLE PRECISION NOT NULL CHECK (longitud BETWEEN -92.5 AND -75.0),
    creada_en    TIMESTAMPTZ      NOT NULL DEFAULT now()
);

-- Cada usuario pertenece a una sola comunidad (UNIQUE usuario_id).
CREATE TABLE integrante (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comunidad_id  BIGINT      NOT NULL REFERENCES comunidad (id),
    usuario_id    BIGINT      NOT NULL UNIQUE REFERENCES usuario (id),
    es_gestor     BOOLEAN     NOT NULL DEFAULT FALSE,
    activo        BOOLEAN     NOT NULL DEFAULT TRUE,
    alta_en       TIMESTAMPTZ NOT NULL DEFAULT now(),
    baja_en       TIMESTAMPTZ,
    UNIQUE (id, comunidad_id),
    CHECK (NOT es_gestor OR activo)
);
CREATE UNIQUE INDEX uq_integrante_gestor ON integrante (comunidad_id) WHERE es_gestor;
CREATE INDEX ix_integrante_comunidad ON integrante (comunidad_id) WHERE activo;

-- Cupo de 25 integrantes activos (incluido el gestor), garantizado por la base de datos.
-- El bloqueo de la fila de la comunidad serializa altas/reactivaciones concurrentes de una misma comunidad:
-- la segunda transacción espera, y su conteo (nueva instantánea en READ COMMITTED) ya ve el alta de la primera.
CREATE FUNCTION validar_cupo_comunidad() RETURNS trigger AS $$
DECLARE
    activos INTEGER;
BEGIN
    IF NEW.activo THEN
        PERFORM 1 FROM comunidad WHERE id = NEW.comunidad_id FOR UPDATE;
        SELECT count(*) INTO activos
          FROM integrante
         WHERE comunidad_id = NEW.comunidad_id
           AND activo
           AND id IS DISTINCT FROM NEW.id;
        IF activos >= 25 THEN
            RAISE EXCEPTION 'cupo_comunidad_excedido: la comunidad % ya tiene 25 integrantes activos', NEW.comunidad_id
                USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_integrante_cupo
    BEFORE INSERT OR UPDATE OF activo, comunidad_id ON integrante
    FOR EACH ROW EXECUTE FUNCTION validar_cupo_comunidad();

-- Comunidades que cada administrador de evidencias puede revisar.
CREATE TABLE asignacion_revisor (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT      NOT NULL REFERENCES usuario (id),
    comunidad_id  BIGINT      NOT NULL REFERENCES comunidad (id),
    asignada_en   TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (usuario_id, comunidad_id)
);

-- Un huerto por comunidad en el prototipo (UNIQUE comunidad_id).
CREATE TABLE huerto (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comunidad_id  BIGINT           NOT NULL UNIQUE REFERENCES comunidad (id),
    nombre        VARCHAR(120)     NOT NULL,
    descripcion   TEXT             NOT NULL,
    latitud       DOUBLE PRECISION NOT NULL CHECK (latitud BETWEEN -5.1 AND 1.8),
    longitud      DOUBLE PRECISION NOT NULL CHECK (longitud BETWEEN -92.5 AND -75.0),
    creado_en     TIMESTAMPTZ      NOT NULL DEFAULT now()
);

CREATE TABLE planta (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    huerto_id          BIGINT       NOT NULL REFERENCES huerto (id),
    nombre_comun       VARCHAR(100) NOT NULL,
    nombre_cientifico  VARCHAR(120),
    descripcion        TEXT,
    cantidad           INTEGER      NOT NULL CHECK (cantidad >= 0),
    activa             BOOLEAN      NOT NULL DEFAULT TRUE,
    creada_en          TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_planta_huerto ON planta (huerto_id);
