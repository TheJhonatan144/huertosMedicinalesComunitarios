-- Misiones configurables por huerto. Las actividades siguen siendo el registro y la evidencia revisable.
CREATE TABLE mision_plantilla (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    orden INTEGER NOT NULL,
    titulo VARCHAR(140) NOT NULL,
    descripcion TEXT NOT NULL,
    tipo_actividad VARCHAR(30) NOT NULL CHECK (tipo_actividad IN
        ('RIEGO','SIEMBRA','DESHIERBE','ABONADO_ORGANICO','COSECHA','MANTENIMIENTO')),
    puntos_individuales INTEGER NOT NULL DEFAULT 0 CHECK (puntos_individuales >= 0),
    puntos_comunitarios INTEGER NOT NULL DEFAULT 0 CHECK (puntos_comunitarios >= 0),
    progreso INTEGER NOT NULL DEFAULT 0 CHECK (progreso >= 0),
    recurrencia VARCHAR(12) NOT NULL DEFAULT 'UNICA' CHECK (recurrencia IN ('UNICA','DIARIA','SEMANAL','MENSUAL')),
    activa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE mision_dependencia (
    mision_id BIGINT NOT NULL REFERENCES mision_plantilla(id),
    depende_de_id BIGINT NOT NULL REFERENCES mision_plantilla(id),
    PRIMARY KEY (mision_id, depende_de_id),
    CHECK (mision_id <> depende_de_id)
);

CREATE TABLE mision_huerto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    huerto_id BIGINT NOT NULL REFERENCES huerto(id),
    plantilla_id BIGINT NOT NULL REFERENCES mision_plantilla(id),
    estado VARCHAR(15) NOT NULL CHECK (estado IN ('BLOQUEADA','DISPONIBLE','EN_REVISION','COMPLETADA','ENFRIAMIENTO')),
    actividad_id BIGINT UNIQUE REFERENCES actividad(id),
    disponible_desde DATE,
    completada_en TIMESTAMPTZ,
    creada_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (huerto_id, plantilla_id)
);
CREATE INDEX ix_mision_huerto_estado ON mision_huerto (huerto_id, estado);

ALTER TABLE actividad ADD COLUMN mision_huerto_id BIGINT NULL REFERENCES mision_huerto(id);
CREATE UNIQUE INDEX uq_actividad_mision ON actividad (mision_huerto_id) WHERE mision_huerto_id IS NOT NULL;

